export function needsDetailedDiscussion(settings, text, { proactive = false, followup = false } = {}) {
  if (proactive || settings.detailedDiscussionEnabled === false || typeof text !== "string") return false;
  if (/(?:一句话|简短(?:说|回答|点)?|简单说|简要|别展开|不要展开|只要结论|长话短说)/u.test(text)) return false;
  if (/(?:分析|讨论|深入|详细|展开|原理|机制|逻辑|论证|反例|反驳|因果|比较|对比|优缺点|利弊|你怎么看|怎么看待|评价一下|怎么实现|如何实现|怎么判断)/u.test(text)) return true;
  if (text.length >= 20 && /(?:为什么|为何|是否合理|靠不靠谱|怎么理解|有什么区别|有什么影响)/u.test(text)) return true;
  return followup && text.length >= 30 && /(?:但是|不对|可是|反而|这说明|你的意思|难道|明明|未必|不一定|凭什么)/u.test(text);
}

