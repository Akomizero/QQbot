export function wantsIllustratedReply(value) {
  const text=String(value??"");
  if(/(?:不要|不用|别|无需).{0,5}(?:图文|长图|图片版)/u.test(text))return false;
  return /(?:图文版|长图|图片版|(?:用|以|做成|生成|发成).{0,4}图文|图文(?:发送|发我|给我)|(?:^|[，,\s])图文[。！!]?$)/u.test(text.trim());
}

